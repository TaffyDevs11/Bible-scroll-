#!/usr/bin/env node
// Validates all content, then writes precache-manifest.js for the service worker.
//   node tools/build.mjs
// Fails (exit code 1) if any scripture reference is missing from the bundled Bible text.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { validate } from './validate.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const ok = process.argv.includes('--no-validate') ? (console.warn('WARNING: content validation skipped (dev only)'), true) : await validate();
if (!ok) { console.error('\nBuild failed: fix the content errors above.'); process.exit(1); }

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.posix.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(rel)); else out.push(rel);
  }
  return out;
}
const hashOf = (files) => {
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update(fs.readFileSync(path.join(ROOT, f))); }
  return h.digest('hex').slice(0, 12);
};

const shell = [
  'index.html', 'manifest.json',
  ...walk('css'), ...walk('js'),
  ...walk('data').filter((f) => f.endsWith('.json')),
  ...walk('fonts').filter((f) => f.endsWith('.woff2')),
  ...walk('icons'),
].sort();
const bible = walk('data/bible').filter((f) => f.endsWith('.gz')).sort();

const manifest = { version: hashOf([...shell, 'sw.js']), bibleVersion: hashOf(bible), shell: ['./', ...shell], bible };
fs.writeFileSync(path.join(ROOT, 'precache-manifest.js'),
  `// Generated by tools/build.mjs — do not edit by hand.\nself.__PRECACHE = ${JSON.stringify(manifest, null, 1)};\n`);
const kb = (fs2) => (fs2.reduce((n, f) => n + fs.statSync(path.join(ROOT, f)).size, 0) / 1024).toFixed(0);
console.log(`precache-manifest.js: shell ${shell.length} files (${kb(shell)} KB), bible ${bible.length} files (${kb(bible)} KB), version ${manifest.version}`);
