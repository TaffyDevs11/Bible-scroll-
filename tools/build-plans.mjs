#!/usr/bin/env node
// Generates data/plans.json (the five built-in reading plans).
//   node tools/build-plans.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const books = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/books.json'), 'utf8'));
const byId = Object.fromEntries(books.map((b) => [b.id, b]));
const name = (id) => byId[id].name;

const chapters = (id) => Array.from({ length: byId[id].v.length }, (_, i) => [`${name(id)} ${i + 1}`]);

// Evenly spread a list of chapters over N days, merging runs into "Book a-b".
function spread(ids, days) {
  const all = ids.flatMap((id) => byId[id].v.map((_, i) => ({ id, c: i + 1 })));
  const out = [];
  for (let d = 0; d < days; d++) {
    const slice = all.slice(Math.floor((d * all.length) / days), Math.floor(((d + 1) * all.length) / days));
    const refs = [];
    for (const x of slice) {
      const last = refs.at(-1);
      if (last && last.id === x.id && last.to === x.c - 1) last.to = x.c;
      else refs.push({ id: x.id, from: x.c, to: x.c });
    }
    out.push(refs.map((r) => `${name(r.id)} ${r.from}${r.to > r.from ? `-${r.to}` : ''}`));
  }
  return out;
}

const NT = books.filter((b) => b.t === 'NT').map((b) => b.id);

const lifeOfJesus = [
  ['John 1:1-18'], ['Luke 1:26-38'], ['Luke 2:1-20'], ['Luke 2:41-52'],
  ['Matthew 3:13-17', 'Matthew 4:1-11'], ['John 2:1-11'], ['John 3:1-21'], ['John 4:1-26'],
  ['Luke 4:16-30'], ['Luke 5:1-11'], ['Matthew 5:1-16'], ['Matthew 6:5-15', 'Matthew 6:25-34'],
  ['Mark 2:1-12'], ['Mark 4:35-41'], ['Mark 5:21-43'], ['John 6:1-14', 'John 6:35-40'],
  ['Matthew 14:22-33'], ['Luke 10:25-37'], ['Luke 15:1-32'], ['John 9:1-25'],
  ['John 10:1-18'], ['John 11:17-44'], ['Matthew 16:13-20', 'Matthew 17:1-8'], ['Luke 19:1-10'],
  ['Mark 11:1-11'], ['John 13:1-17'], ['Matthew 26:36-56'], ['John 19:16-30'],
  ['Luke 24:1-35'], ['John 21:1-19', 'Acts 1:6-11'],
];

const comfortPsalms = [[23], [27], [46], [91], [121], [34], [139], [103], [62], [42, 43], [16], [40], [145], [131, 4]]
  .map((d) => d.map((n) => `Psalm ${n}`));

const plans = [
  { id: 'john-21', title: 'Gospel of John', length: 21, summary: 'Read the whole Gospel of John, one chapter a day, and meet Jesus the Word.', days: chapters('JHN') },
  { id: 'life-of-jesus-30', title: 'Life of Jesus', length: 30, summary: 'Walk with Jesus from His birth to His resurrection in thirty short readings.', days: lifeOfJesus },
  { id: 'psalms-comfort-14', title: 'Psalms of comfort', length: 14, summary: 'Fourteen psalms for hard days, to pray as well as read.', days: comfortPsalms },
  { id: 'proverbs-31', title: 'Proverbs', length: 31, summary: 'A chapter of practical wisdom for every day of the month.', days: chapters('PRO') },
  { id: 'nt-90', title: 'New Testament in 90 days', length: 90, summary: 'Read the whole New Testament in about three chapters a day.', days: spread(NT, 90) },
];

fs.writeFileSync(path.join(ROOT, 'data/plans.json'), JSON.stringify({ note: 'Generated by tools/build-plans.mjs', plans }, null, 1));
console.log(plans.map((p) => `${p.id}: ${p.days.length} days`).join('\n'));
